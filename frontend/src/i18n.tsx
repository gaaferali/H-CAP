export function translateArabic(value: string) {
  const trimmed = value.trim();
  const codeKey = trimmed.replaceAll(" ", "_").toUpperCase();
  const direct = arabic[value] ?? arabic[trimmed] ?? arabic[codeKey] ?? arabicInline[value] ?? arabicInline[trimmed];
  if (direct) return value.replace(trimmed, direct);
  return Object.entries(arabicInline)
    .sort(([first], [second]) => second.length - first.length)
    .reduce(
      (localized, [source, replacement]) =>
        localized.replaceAll(source, replacement),
      value,
    );
}

export const TranslationContext = createContext<(value: string) => string>(
  (value) => value,
);
export const useTranslation = () => useContext(TranslationContext);

export function TranslateTree({ children }: { children: ReactNode }) {
  const translate = useTranslation();
  const localize = (node: ReactNode): ReactNode => {
    if (typeof node === "string") return translate(node);
    if (Array.isArray(node)) return node.map((item) => localize(item));
    if (
      isValidElement<{ children?: ReactNode }>(node) &&
      node.props.children !== undefined
    ) {
      return cloneElement(node, undefined, localize(node.props.children));
    }
    return node;
  };
  return <>{localize(children)}</>;
}
